SELECT
    substr(date, 1, 7) AS month,
    decimal_sum(total_aws_unblended_cost) AS total_aws_unblended_cost,
    decimal_sum(total_aws_calculated_amortized_cost) AS total_aws_calculated_amortized_cost,
    decimal_sum(total_azure_pretax_cost) AS total_azure_pretax_cost,
    decimal_sum(total_gcp_unblended_cost) AS total_gcp_unblended_cost,
    decimal_sum(total_gcp_total) AS total_gcp_total,
    decimal_sum(total_total_infrastructure_raw_cost) AS total_total_infrastructure_raw_cost,
    decimal_sum(total_total_cost_model_costs) AS total_total_cost_model_costs,
    decimal_sum(total_infra_total_cost_model) AS total_infra_total_cost_model,
    decimal_sum(total_infra_cost_model_cpu_cost) AS total_infra_cost_model_cpu_cost,
    decimal_sum(total_infra_cost_model_memory_cost) AS total_infra_cost_model_memory_cost,
    decimal_sum(total_infra_cost_model_volume_cost) AS total_infra_cost_model_volume_cost,
    decimal_sum(total_sup_total_cost_model) AS total_sup_total_cost_model,
    decimal_sum(total_sup_cost_model_cpu_cost) AS total_sup_cost_model_cpu_cost,
    decimal_sum(total_sup_cost_model_memory_cost) AS total_sup_cost_model_memory_cost,
    decimal_sum(total_sup_cost_model_volume_cost) AS total_sup_cost_model_volume_cost,
    MAX(total_cluster_count) AS total_cluster_count,
    MAX(total_node_count) AS total_node_count,
    MAX(total_infra_node_count) as total_infra_node_count,
    MAX(total_control_plane_node_count) as total_control_plane_node_count,
    MAX(total_worker_node_count) as total_worker_node_count,
    decimal_max(total_infra_node_cpu_cores) AS total_infra_node_cpu_cores,
    decimal_max(total_control_plane_node_cpu_cores) AS total_control_plane_node_cpu_cores,
    decimal_max(total_worker_node_cpu_cores) AS total_worker_node_cpu_cores,
    decimal_max(total_infra_node_mem_gb) AS total_infra_node_mem_gb,
    decimal_max(total_control_plane_node_mem_gb) AS total_control_plane_node_mem_gb,
    decimal_max(total_worker_node_mem_gb) AS total_worker_node_mem_gb,
    MAX(total_pvc_count) AS total_pvc_count,
    decimal_max(total_cluster_capacity_cores) AS total_cluster_capacity_cores,
    decimal_sum(total_cluster_capacity_core_hours) AS total_cluster_capacity_core_hours,
    decimal_max(total_cluster_capacity_memory_gb) AS total_cluster_capacity_memory_gb,
    decimal_sum(total_cluster_capacity_memory_gb_hours) AS total_cluster_capacity_memory_gb_hours,
    decimal_max(total_volume_request_gb) AS total_volume_request_gb,
    decimal_sum(total_volume_request_gb_mo) AS total_volume_request_gb_mo,
    decimal_max(total_pvc_capacity_gb) AS total_pvc_capacity_gb,
    decimal_sum(total_pvc_capacity_gb_mo) AS total_pvc_capacity_gb_mo
FROM __customer_total_data
GROUP BY substr(date, 1, 7)
ORDER BY substr(date, 1, 7)
;
